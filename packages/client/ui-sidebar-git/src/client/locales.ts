/**
 * `sidebarGit` namespace dictionaries, and the namespace's declaration.
 *
 * The failure lines name one code each: a missing repository, a refused
 * branch name, a bad commit message, a bad path, and an oversized diff each
 * suggest a different next step, and a failed git command carries its stderr
 * beside the generic line. The namespace merge lives with its key set so that
 * any module naming `TranslateNS<'sidebarGit'>` or `PropsLocale<'sidebarGit'>`
 * needs only this file, whichever entry a program loads first.
 */
