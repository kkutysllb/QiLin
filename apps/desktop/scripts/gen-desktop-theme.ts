/**
 * Generate the desktop shell's two pre-Web surfaces from one color pack:
 * the welcome renderer palette and the Windows installer palette.
 *
 * Both artifacts come from the product's default pack
 * (@qilin-agent/client-ui-theme-brand), so the welcome window and the installer
 * follow the same colors as the product default skin. Run with --check to fail
 * when a committed artifact is stale.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { QILIN_PACK } from '@qilin-agent/client-ui-theme-brand/src/skin.ts'

/** Repository-relative destination of the welcome renderer palette. */
const WELCOME_CSS = 'apps/desktop/renderer/welcome-palette.generated.css'

/** Repository-relative destination of the installer palette. */
const INSTALLER_NSH = 'apps/desktop/installer/theme.generated.nsh'

/** Welcome stylesheet roles, mapped onto pack tokens. */
const WELCOME_ROLES: readonly (readonly [string, string])[] = [
  ['--dsw-alias-label-primary', '--qilin-alias-label-primary'],
  ['--dsw-alias-label-secondary', '--qilin-alias-label-secondary'],
  ['--dsw-alias-label-tertiary', '--qilin-alias-label-tertiary'],
  ['--dsw-alias-label-caption', '--qilin-alias-label-caption'],
  ['--dsw-alias-label-primary-inverted', '--qilin-alias-label-primary-inverted'],
  ['--dsw-alias-brand-primary', '--qilin-alias-brand-primary'],
  ['--dsw-alias-button-primary-hover', '--qilin-alias-button-primary-hover'],
  ['--dsw-alias-button-elevated-fill', '--qilin-alias-button-elevated-fill'],
  ['--dsw-alias-button-floating-hover', '--qilin-alias-button-floating-hover'],
  ['--dsw-alias-border-l2', '--qilin-alias-border-l2'],
  ['--dsw-alias-border-l4', '--qilin-alias-border-l4'],
]

interface Rgb {
  r: number
  g: number
  b: number
  a: number
}

function channel(value: string, base: number): number {
  return Number.parseInt(value, base)
}

/** Parse one pack color into channels; the packs use hex and rgba() only. */
function parse(value: string): Rgb {
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/iu.exec(value)
  if (hex !== null) {
    const body = hex[1]!
    const full = body.length === 3 ? body.split('').map(digit => digit + digit).join('') : body
    return {
      r: channel(full.slice(0, 2), 16), g: channel(full.slice(2, 4), 16), b: channel(full.slice(4, 6), 16), a: 1,
    }
  }
  const rgba = /^rgba?\(([^)]*)\)$/iu.exec(value)
  if (rgba === null) throw new Error(`desktop theme: unsupported color ${value}`)
  const parts = rgba[1]!.split(',').map(part => part.trim())
  if (parts.length !== 3 && parts.length !== 4) throw new Error(`desktop theme: unsupported color ${value}`)
  return {
    r: channel(parts[0]!, 10),
    g: channel(parts[1]!, 10),
    b: channel(parts[2]!, 10),
    a: parts.length === 4 ? Number.parseFloat(parts[3]!) : 1,
  }
}

function hex(value: Rgb): string {
  const channelHex = (part: number): string => Math.max(0, Math.min(255, Math.round(part))).toString(16).padStart(2, '0')
  return `#${channelHex(value.r)}${channelHex(value.g)}${channelHex(value.b)}`
}

/** Composite a translucent color over an opaque background (NSIS has no alpha). */
function solid(value: string, background: string): string {
  const front = parse(value)
  if (front.a >= 1) return hex(front)
  const back = parse(background)
  return hex({
    r: front.r * front.a + back.r * (1 - front.a),
    g: front.g * front.a + back.g * (1 - front.a),
    b: front.b * front.a + back.b * (1 - front.a),
    a: 1,
  })
}

/** Shift a color toward black by `ratio`; used for the installer's pressed state. */
function darken(value: string, ratio: number): string {
  const color = parse(value)
  return hex({ r: color.r * (1 - ratio), g: color.g * (1 - ratio), b: color.b * (1 - ratio), a: 1 })
}

function tokenValue(token: string, mode: 'light' | 'dark'): string {
  const modes = QILIN_PACK.tokens[token]
  if (modes === undefined) throw new Error(`desktop theme: pack ${QILIN_PACK.id} has no ${token}`)
  return modes[mode]
}

/** GDI+ ARGB literal, uppercase. */
function argb(color: string): string {
  return `0xFF${solid(color, '#000000').slice(1).toUpperCase()}`
}

/** GDI COLORREF literal: BGR order, uppercase digits. */
function colorref(color: string): string {
  const value = solid(color, '#000000')
  return `0x${`${value.slice(5, 7)}${value.slice(3, 5)}${value.slice(1, 3)}`.toUpperCase()}`
}

/** Bare six-digit hex for SetCtlColors and window background strings. */
function bare(color: string): string {
  return solid(color, '#000000').slice(1).toUpperCase()
}

function welcomeCss(): string {
  const modes = (mode: 'light' | 'dark'): string => WELCOME_ROLES
    .map(([role, token]) => `  ${role}: ${tokenValue(token, mode)};`)
    .join('\n')
  return `/* Generated by apps/desktop/scripts/gen-desktop-theme.ts from pack ${QILIN_PACK.id}; do not edit. */
body {
${modes('light')}
}

@media (prefers-color-scheme: dark) {
  body {
${modes('dark').split('\n').map(line => `  ${line}`).join('\n')}
  }
}

body[data-ds-dark-theme] {
${modes('dark')}
}
`
}

function installerPalette(mode: 'light' | 'dark'): string {
  const prefix = mode.toUpperCase()
  const background = tokenValue('--qilin-alias-bg-base', mode)
  const text = tokenValue('--qilin-alias-label-primary', mode)
  const primary = tokenValue('--qilin-alias-brand-primary', mode)
  const hover = tokenValue('--qilin-alias-button-primary-hover', mode)
  const pressed = darken(solid(hover, background), 0.16)
  const controlHover = solid(tokenValue('--qilin-alias-interactive-bg-hover-solid', mode), background)
  const track = solid(tokenValue('--qilin-alias-scrollbar-bg-l1', mode), background)
  const buttonText = tokenValue('--qilin-alias-label-primary-inverted', mode)
  const border = solid(tokenValue('--qilin-alias-button-ghost-active-border', mode), background)
  return [
    `!define INSTALLER_${prefix}_BG_HEX "${bare(background)}"`,
    `!define INSTALLER_${prefix}_TEXT_HEX "${bare(text)}"`,
    `!define INSTALLER_${prefix}_BG_ARGB ${argb(background)}`,
    `!define INSTALLER_${prefix}_BG_COLORREF ${colorref(background)}`,
    `!define INSTALLER_${prefix}_TEXT_COLORREF ${colorref(text)}`,
    `!define INSTALLER_${prefix}_PRIMARY_ARGB ${argb(primary)}`,
    `!define INSTALLER_${prefix}_PRIMARY_HOVER_ARGB ${argb(hover)}`,
    `!define INSTALLER_${prefix}_PRIMARY_PRESSED_ARGB ${argb(pressed)}`,
    `!define INSTALLER_${prefix}_CONTROL_HOVER_ARGB ${argb(controlHover)}`,
    `!define INSTALLER_${prefix}_TRACK_ARGB ${argb(track)}`,
    `!define INSTALLER_${prefix}_BUTTON_TEXT_COLORREF ${colorref(buttonText)}`,
    `!define INSTALLER_${prefix}_BORDER_ARGB ${argb(border)}`,
  ].join('\n')
}

function installerNsh(): string {
  return `; Generated by apps/desktop/scripts/gen-desktop-theme.ts from pack ${QILIN_PACK.id}; do not edit.
${installerPalette('light')}

${installerPalette('dark')}
`
}

const root = fileURLToPath(new URL('../../../', import.meta.url))

const outputs: readonly (readonly [string, string])[] = [
  [WELCOME_CSS, welcomeCss()],
  [INSTALLER_NSH, installerNsh()],
]

const check = process.argv.includes('--check')
let stale = 0
for (const [path, content] of outputs) {
  const target = resolve(root, path)
  if (check) {
    let current = ''
    try {
      current = readFileSync(target, 'utf8')
    } catch {
      // A missing artifact is stale, not an error.
    }
    if (current !== content) {
      stale += 1
      console.error(`gen-desktop-theme: ${path} is stale; run pnpm run gen-desktop-theme`)
    }
  } else {
    writeFileSync(target, content)
  }
}
if (check && stale > 0) process.exit(1)
console.log(check ? 'gen-desktop-theme: desktop palettes are current' : `gen-desktop-theme: wrote ${outputs.length} artifact(s)`)
