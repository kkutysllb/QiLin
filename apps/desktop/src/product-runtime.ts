/** Runtime facts one product launch needs before the Host starts. */
export interface DesktopProductPaths {
  readonly dataDir: string
  readonly harnessHome: string
  readonly profileDir: string
  readonly pluginDir?: string | undefined
  readonly presetsDir?: string | undefined
  readonly runtimeDir?: string | undefined
  /** Runtime package root the Host resolves `@qilin-agent/desktop-host` from. */
  readonly qilinDir: string
  /** Directory holding the Electron Node shim. */
  readonly nodeBin: string
  /** Bundled pnpm entry. */
  readonly pnpm: string
}

/** Launch facts that select layout and identity. */
export interface PrepareProductRuntimeOptions {
  readonly product: DesktopProduct
  readonly root: string
  readonly packaged: boolean
  readonly resourcesPath: string
  /** Product version, exposed to the client build. */
  readonly version: string
  readonly home?: string | undefined
  readonly electronExecutable?: string | undefined
  /** Receives one-line progress messages. */
  readonly log?: ((message: string) => void) | undefined
}

/** One plugin package discovered under the product plugin root. */
export interface ProductPlugin {
  readonly name: string
  readonly directory: string
}

const HOST_ENTRY = join('node_modules', '@qilin-agent', 'desktop-host', 'lib', 'index.js')

function fail(message: string): never {
  throw new Error(message)
}

function stampOf(tarPath: string): string {
  const stat = statSync(tarPath)
  return `${String(stat.size)}:${String(Math.trunc(stat.mtimeMs))}`
}

/**
 * Extract a bundled runtime archive once per content fingerprint.
 * @param tarPath - Archive the application ships.
 * @param destination - Runtime directory owned by this installation.
 * @param log - Progress sink.
 * @returns The extracted runtime root.
 */
export function ensureRuntimeExtracted(
  tarPath: string,
  destination: string,
  log: (message: string) => void = () => {},
): string {
  const entry = join(destination, HOST_ENTRY)
  if (existsSync(entry)) {
    try {
      if (readFileSync(join(destination, '.runtime-stamp'), 'utf8') === stampOf(tarPath)) return destination
    } catch {
      // A missing stamp means an unfinished or unknown extraction; extract again.
    }
  }
  log('desktop runtime: extracting bundled archive')
  const temporary = `${destination}.tmp-${String(process.pid)}`
  rmSync(temporary, { recursive: true, force: true })
  mkdirSync(temporary, { recursive: true })
  const result = spawnSync('tar', ['-xzf', tarPath, '-C', temporary], { timeout: 300_000, windowsHide: true })
  if (result.status !== 0 || !existsSync(join(temporary, HOST_ENTRY))) {
    rmSync(temporary, { recursive: true, force: true })
    throw new Error(`desktop runtime: extraction failed: ${result.stderr?.toString() || `tar exit ${String(result.status)}`}`)
  }
  writeFileSync(join(temporary, '.runtime-stamp'), stampOf(tarPath))
  rmSync(destination, { recursive: true, force: true })
  renameSync(temporary, destination)
  return destination
}

/**
 * Write the pnpm and node launchers that run inside the bundled runtime.
 * @param runtimeDir - Extracted runtime root.
 * @param electron - Electron executable, used as the Node runtime.
 * @param log - Progress sink.
 * @returns Directory holding both launchers.
 */
export function ensureRuntimeLaunchers(
  runtimeDir: string,
  electron: string,
  log: (message: string) => void = () => {},
): string {
  const bin = join(runtimeDir, 'tools', 'pnpm', 'bin')
  mkdirSync(bin, { recursive: true })
  const pnpmEntry = join(bin, 'pnpm.cjs')
  const windows = platform() === 'win32'
  if (existsSync(pnpmEntry)) {
    const shim = join(bin, windows ? 'pnpm.cmd' : 'pnpm')
    const body = windows
      ? `@echo off\r\nset ELECTRON_RUN_AS_NODE=1\r\n"${electron}" "${pnpmEntry}" %*\r\n`
      : `#!/bin/sh\n# Generated by the desktop product runtime; do not edit.\nELECTRON_RUN_AS_NODE=1 exec "${electron}" "${pnpmEntry}" "$@"\n`
    writeLauncher(shim, body)
  }
  const nodeShim = join(bin, windows ? 'node.cmd' : 'node')
  writeLauncher(nodeShim, windows
    ? `@echo off\r\nset ELECTRON_RUN_AS_NODE=1\r\n"${electron}" %*\r\n`
    : `#!/bin/sh\n# Generated by the desktop product runtime; do not edit.\nELECTRON_RUN_AS_NODE=1 exec "${electron}" "$@"\n`)
  log(`desktop runtime: launchers ready in ${bin}`)
  return bin
}

function writeLauncher(path: string, body: string): void {
  if (existsSync(path)) {
    try {
      if (readFileSync(path, 'utf8') === body) return
    } catch {
      // An unreadable launcher is replaced below.
    }
  }
  rmSync(path, { force: true })
  writeFileSync(path, body, { mode: 0o755 })
}

/**
 * List product plugin packages by reading each child directory's manifest.
 * @param root - Product plugin root.
 * @returns Packages in directory order.
 */
export function discoverProductPlugins(root: string): readonly ProductPlugin[] {
  if (!existsSync(root)) return []
  const plugins: ProductPlugin[] = []
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const directory = join(root, entry.name)
    try {
      const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8')) as { name?: unknown }
      if (typeof manifest.name === 'string' && manifest.name.includes('/')) {
        plugins.push({ name: manifest.name, directory })
      }
    } catch {
      // A directory without a readable manifest is not a plugin package.
    }
  }
  return plugins
}

/**
 * Seed the product profile: bundle layers plus one relative link per plugin.
 * @param profileDir - Profile directory the Host boots.
 * @param product - Product manifest.
 * @param plugins - Discovered plugin packages.
 * @param log - Progress sink.
 * @param runtimeDir - Extracted runtime whose `node_modules` resolves engine bundle layers.
 */
export function seedProductProfile(
  profileDir: string,
  product: DesktopProduct,
  plugins: readonly ProductPlugin[],
  log: (message: string) => void = () => {},
  runtimeDir?: string,
): void {
  mkdirSync(profileDir, { recursive: true, mode: 0o700 })
  initProfile(profileDir, product.profileBundles)
  const manifestPath = join(profileDir, 'package.json')
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
    dependencies?: Record<string, string>
    qilin?: { profile?: { bundles?: string[] } }
  }
  const dependencies: Record<string, string> = { ...manifest.dependencies }
  for (const plugin of plugins) dependencies[plugin.name] = `link:${plugin.directory}`
  const existing = manifest.qilin?.profile?.bundles ?? []
  // KStock patch (K41): a bundle the plugin manager removed but left in the layer
  // list makes the strict profile loader refuse to boot. Drop layers that resolve
  // from neither this profile nor the runtime; the product layers always do.
  const extras = existing.filter(bundle => !product.profileBundles.includes(bundle))
  const keptExtras = extras.filter(bundle => bundleInstalled(profileDir, runtimeDir, bundle))
  const dropped = extras.filter(bundle => !keptExtras.includes(bundle))
  if (dropped.length > 0) log(`desktop profile: dropped unresolvable bundle(s): ${dropped.join(', ')}`)
  const missing = product.profileBundles.filter(bundle => !existing.includes(bundle))
  const bundles = [...product.profileBundles, ...keptExtras]
  const dependenciesChanged = plugins.some(plugin => manifest.dependencies?.[plugin.name] !== `link:${plugin.directory}`)
  if (dependenciesChanged || missing.length > 0 || dropped.length > 0) {
    writeFileSync(manifestPath, `${JSON.stringify({
      ...manifest,
      dependencies,
      qilin: { ...manifest.qilin, profile: { ...manifest.qilin?.profile, bundles } },
    }, undefined, 2)}\n`)
    log('desktop profile: manifest updated')
  }
  for (const plugin of plugins) linkPlugin(profileDir, plugin)
}

/** Whether a profile layer resolves from the profile or the extracted runtime. */
function bundleInstalled(profileDir: string, runtimeDir: string | undefined, name: string): boolean {
  const roots = [join(profileDir, 'node_modules'), ...(runtimeDir === undefined ? [] : [join(runtimeDir, 'node_modules')])]
  return roots.some(root => existsSync(join(root, name, 'package.json')))
}

function linkPlugin(profileDir: string, plugin: ProductPlugin): void {
  const [scope, name] = plugin.name.split('/')
  if (scope === undefined || name === undefined) return
  const directory = join(profileDir, 'node_modules', scope)
  mkdirSync(directory, { recursive: true })
  const link = join(directory, name)
  if (existsSync(link)) {
    try {
      if (resolve(dirname(link), readlinkSync(link)) === resolve(plugin.directory)) return
    } catch {
      // A plain directory is not a managed link; replace it.
    }
    rmSync(link, { recursive: true, force: true })
  }
  symlinkSync(plugin.directory, link, platform() === 'win32' ? 'junction' : 'dir')
}

/** Python interpreter a bundled skill script can run under. */
interface PythonLauncher {
  readonly bin: string
  readonly prefix: readonly string[]
}

const PYTHON_PACKAGES = ['pandas', 'numpy', 'requests', 'python-dotenv', 'tushare', 'matplotlib'] as const
const PYTHON_MODULES = 'pandas, numpy, requests, dotenv, tushare, matplotlib'

function resolvePython(): PythonLauncher | undefined {
  for (const candidate of [
    { bin: 'python3', prefix: [] },
    { bin: 'python', prefix: [] },
    { bin: 'py', prefix: ['-3'] },
  ]) {
    const probe = spawnSync(candidate.bin, [...candidate.prefix, '--version'], { encoding: 'utf8', timeout: 15_000, windowsHide: true })
    if (probe.status === 0) return candidate
  }
  return undefined
}

/**
 * Install the Python packages the bundled skill scripts import, once per interpreter.
 *
 * The install targets `<data>/py-deps`, which the Host already carries on PYTHONPATH.
 * It never blocks the window and never fails launch: a machine without Python, without
 * network, or with a broken pip keeps the product running with degraded data skills.
 * @param options - Data directory, inherited Host environment, and progress sink.
 * @returns Resolves when the probe finishes or the install attempt settles.
 */
export async function ensurePythonDependencies(options: {
  readonly dataDir: string
  readonly environment: Readonly<Record<string, string>>
  readonly log: (message: string) => void
}): Promise<void> {
  if (process.env.KSTOCK_SKIP_DEP_BOOTSTRAP === '1') return
  const target = join(options.dataDir, 'py-deps')
  if (existsSync(join(target, '.deps-ok'))) return
  const launcher = resolvePython()
  if (launcher === undefined) {
    options.log('desktop python: no interpreter found; data skills run without the optional packages')
    return
  }
  const offline = { ...process.env, ...options.environment } as NodeJS.ProcessEnv
  const probe = spawnSync(launcher.bin, [...launcher.prefix, '-c', `import ${PYTHON_MODULES}`], {
    env: offline, timeout: 30_000, windowsHide: true,
  })
  if (probe.status === 0) {
    mkdirSync(target, { recursive: true })
    writeFileSync(join(target, '.deps-ok'), 'available\n')
    return
  }
  options.log('desktop python: installing skill dependencies into the product data directory')
  await new Promise<void>((resolvePromise) => {
    const child = spawn(launcher.bin, [
      ...launcher.prefix, '-m', 'pip', 'install', '--target', target, ...PYTHON_PACKAGES,
    ], { env: offline, stdio: 'ignore', windowsHide: true })
    child.once('error', (error: unknown) => {
      options.log(`desktop python: dependency install failed (${error instanceof Error ? error.message : String(error)})`)
      resolvePromise()
    })
    child.once('exit', (code) => {
      if (code === 0) {
        mkdirSync(target, { recursive: true })
        writeFileSync(join(target, '.deps-ok'), 'installed\n')
      } else {
        options.log(`desktop python: dependency install exited ${String(code)}; data skills degrade`)
      }
      resolvePromise()
    })
  })
}

/**
 * Read legacy data-source credentials from `<data>/config/secrets.env`.
 * @param dataDir - Product data directory.
 * @returns Environment entries the file declares.
 */
export function readLegacySecrets(dataDir: string): Readonly<Record<string, string>> {
  const path = join(dataDir, 'config', 'secrets.env')
  if (!existsSync(path)) return {}
  const secrets: Record<string, string> = {}
  try {
    for (const line of readFileSync(path, 'utf8').split(/\r?\n/u)) {
      const trimmed = line.trim()
      if (trimmed === '' || trimmed.startsWith('#')) continue
      const equals = trimmed.indexOf('=')
      if (equals <= 0) continue
      const key = trimmed.slice(0, equals).trim()
      if (!/^[A-Z_][A-Z0-9_]*$/iu.test(key)) continue
      let value = trimmed.slice(equals + 1).trim()
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1)
      }
      if (value !== '') secrets[key] = value
    }
  } catch {
    return {}
  }
  return secrets
}

/**
 * Prepare extraction, profile seeding, and the Host environment for one launch.
 * @param options - Launch facts.
 * @returns Paths and environment entries the shell applies before starting the Host.
 */
export function prepareProductRuntime(options: PrepareProductRuntimeOptions): {
  readonly paths: DesktopProductPaths
  readonly environment: Readonly<Record<string, string>>
} {
  const log = options.log ?? (() => {})
  const electron = options.electronExecutable ?? process.execPath
  const home = options.home ?? homedir()
  const dataDir = productDataDirectory(options.product, options.packaged, home)
  const harnessHome = productHarnessHome(options.product, options.packaged, home)
  const profileDir = join(harnessHome, 'profiles', options.product.profile)
  const pluginDir = productPluginDirectory(options.product, options.root, options.packaged)
  const presetsDir = productPresetsDirectory(options.product, options.root, options.packaged)
  mkdirSync(dataDir, { recursive: true, mode: 0o700 })
  mkdirSync(harnessHome, { recursive: true, mode: 0o700 })

  const override = process.env.QILIN_DESKTOP_CLI_DIR
  let runtimeDir: string | undefined = override === undefined || override === '' ? undefined : override
  if (runtimeDir === undefined && options.product.runtime !== undefined) {
    const tar = productRuntimeTar(options.product, options.root, options.packaged, options.resourcesPath)
    if (tar === undefined || !existsSync(tar)) {
      throw new Error(`desktop runtime: bundled archive is missing (${String(tar)})`)
    }
    runtimeDir = ensureRuntimeExtracted(tar, join(dataDir, options.packaged ? 'runtime' : 'runtime-dev'), log)
  }
  const qilinDir = runtimeDir ?? fail('desktop runtime: no bundled runtime and QILIN_DESKTOP_CLI_DIR is unset')
  const nodeBin = ensureRuntimeLaunchers(qilinDir, electron, log)
  const pnpm = join(qilinDir, 'tools', 'pnpm', 'bin', 'pnpm.cjs')
  const launcherBin = join(qilinDir, 'tools', 'pnpm', 'bin')

  const plugins = pluginDir === undefined ? [] : discoverProductPlugins(pluginDir)
  seedProductProfile(profileDir, options.product, plugins, log, qilinDir)

  const secret = options.product.auth.mode === 'boot-secret'
    ? randomBytes(32).toString('base64url')
    : undefined
  const environment: Record<string, string> = {
    QILIN_HOME: harnessHome,
    QILIN_DESKTOP_HOME: harnessHome,
    QILIN_DESKTOP_PROFILE: options.product.profile,
    QILIN_DESKTOP_OFFICE: options.product.office ? '1' : '0',
    QILIN_CLIENT_PRODUCT_VERSION: options.version,
    // KStock patch (K37): the bundled pnpm shim must lead the Host PATH. A GUI launch inherits
    // the launchd PATH with no user package manager, and the plugin manager spawns `pnpm`
    // directly; the shims in tools/pnpm/bin are the only guaranteed executable.
    PATH: [launcherBin, process.env.PATH].filter((value): value is string => typeof value === 'string' && value !== '').join(delimiter),
    PYTHONPATH: [join(dataDir, 'py-deps'), process.env.PYTHONPATH].filter((value): value is string => typeof value === 'string' && value !== '').join(delimiter),
  }
  if (secret !== undefined) environment[options.product.auth.secretEnv] = secret
  for (const [name, value] of Object.entries(options.product.env ?? {})) {
    environment[name] = expand(value, { dataDir, harnessHome, pluginDir, presetsDir, version: options.version })
  }
  for (const [name, value] of Object.entries(readLegacySecrets(dataDir))) {
    if (process.env[name] === undefined) environment[name] = value
  }
  return {
    paths: { dataDir, harnessHome, profileDir, pluginDir, presetsDir, runtimeDir, qilinDir, nodeBin, pnpm },
    environment,
  }
}

function expand(value: string, facts: {
  readonly dataDir: string
  readonly harnessHome: string
  readonly pluginDir?: string | undefined
  readonly presetsDir?: string | undefined
  readonly version: string
}): string {
  return value
    .replaceAll('$dataDir', facts.dataDir)
    .replaceAll('$harnessHome', facts.harnessHome)
    .replaceAll('$pluginDir', facts.pluginDir ?? '')
    .replaceAll('$presetsDir', facts.presetsDir ?? '')
    .replaceAll('$version', facts.version)
}
